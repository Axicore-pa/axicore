const fs=require('node:fs'),assert=require('node:assert/strict');
const {PGlite}=require(require.resolve('@electric-sql/pglite',{paths:[__dirname,process.env.AXICORE_SQL_MODULES||__dirname]}));
(async()=>{
const db=new PGlite();
await db.exec(`CREATE SCHEMA private; CREATE SCHEMA storage;
CREATE ROLE authenticated;
CREATE FUNCTION private.es_ceo() RETURNS boolean LANGUAGE sql AS $$SELECT current_setting('test.ceo',true)='yes'$$;
CREATE FUNCTION storage.extension(name text) RETURNS text LANGUAGE sql AS $$SELECT reverse(split_part(reverse(name),'.',1))$$;
CREATE TABLE storage.buckets(id text primary key,file_size_limit bigint);
INSERT INTO storage.buckets VALUES ('mant-evidencia',NULL),('other',42);
CREATE TABLE storage.objects(bucket_id text,name text);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE POLICY axi_mantev_subir ON storage.objects FOR INSERT TO authenticated WITH CHECK(bucket_id='mant-evidencia' AND private.es_ceo());
GRANT USAGE ON SCHEMA storage,private TO authenticated;
GRANT INSERT ON storage.objects TO authenticated;
CREATE FUNCTION public.fn_set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN NEW.updated_at=now();RETURN NEW;END$$;
CREATE TABLE public.fixture(id integer,updated_at timestamptz);
CREATE TRIGGER fixture_update BEFORE UPDATE ON public.fixture FOR EACH ROW EXECUTE FUNCTION public.fn_set_updated_at();
INSERT INTO public.fixture VALUES (1,NULL);`);
await db.exec(fs.readFileSync(__dirname+'/../sql/endurecimiento_inmediato.sql','utf8'));
assert.equal((await db.query("SELECT file_size_limit FROM storage.buckets WHERE id='mant-evidencia'")).rows[0].file_size_limit,10485760);
assert.equal((await db.query("SELECT file_size_limit FROM storage.buckets WHERE id='other'")).rows[0].file_size_limit,42);
await db.exec('UPDATE public.fixture SET id=2');
assert.ok((await db.query('SELECT updated_at FROM public.fixture')).rows[0].updated_at);
await db.exec("SET ROLE authenticated; SELECT set_config('test.ceo','yes',false)");
for(const name of ['photo.png','photo.jpg','photo.JPEG'])await db.query('INSERT INTO storage.objects VALUES ($1,$2)',['mant-evidencia',name]);
for(const name of ['photo.svg','photo.html','photo.jpg.exe','photo'])await assert.rejects(db.query('INSERT INTO storage.objects VALUES ($1,$2)',['mant-evidencia',name]));
await assert.rejects(db.query('INSERT INTO storage.objects VALUES ($1,$2)',['other','photo.jpg']));
await db.exec("SELECT set_config('test.ceo','no',false)");
await assert.rejects(db.query('INSERT INTO storage.objects VALUES ($1,$2)',['mant-evidencia','photo.jpg']));
await db.exec('RESET ROLE');
await db.exec(fs.readFileSync(__dirname+'/../sql/rollback_endurecimiento_inmediato.sql','utf8'));
assert.equal((await db.query("SELECT file_size_limit FROM storage.buckets WHERE id='mant-evidencia'")).rows[0].file_size_limit,null);
await db.close();console.log('OK límites, trigger, extensiones permitidas/prohibidas, autorización y reversión');
})();
