CREATE OR REPLACE FUNCTION private.contacto_submit(p_fields jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE r record; k text; v_actual text; n int := 0; v_uid uuid := (SELECT auth.uid());
BEGIN
  IF NOT private.es_residente() THEN RAISE EXCEPTION 'Solo propietarios e inquilinos' USING ERRCODE = '42501'; END IF;
  p_fields := jsonb_strip_nulls(p_fields);
  IF p_fields = '{}'::jsonb THEN RAISE EXCEPTION 'No hay datos para actualizar' USING ERRCODE = '22023'; END IF;
  FOREACH k IN ARRAY ARRAY['telefono','whatsapp','contacto_emergencia_telefono'] LOOP
    IF p_fields ? k AND (p_fields->>k) !~ '^[0-9+() .-]{7,25}$' THEN RAISE EXCEPTION 'Telefono no valido (%)', k USING ERRCODE = '22023'; END IF;
  END LOOP;
  IF p_fields ? 'email' AND (length(p_fields->>'email') > 254 OR (p_fields->>'email') !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') THEN
    RAISE EXCEPTION 'Correo no valido' USING ERRCODE = '22023'; END IF;
  FOR r IN SELECT 'propietarios'::text AS t, p.id, p.condominio_id, p.nombre, 'Propietario'::text AS rol, to_jsonb(p) AS j
             FROM public.propietarios p WHERE p.id = ANY (private.mis_propietarios())
           UNION ALL
           SELECT 'inquilinos', i.id, i.condominio_id, i.nombre, 'Inquilino', to_jsonb(i)
             FROM public.inquilinos i WHERE i.id = ANY (private.mis_inquilinos()) LOOP
    FOR k IN SELECT jsonb_object_keys(p_fields) LOOP
      v_actual := r.j->>k;
      CONTINUE WHEN v_actual IS NOT DISTINCT FROM p_fields->>k;
      UPDATE public.solicitudes_autorizacion s SET valor_nuevo = p_fields->>k, fecha_solicitud = now(), updated_at = now()
       WHERE s.modulo = 'Residentes' AND s.tabla = r.t AND s.registro_id = r.id AND s.campo = k
         AND s.estado_solicitud IN ('Sometido','En proceso');
      IF NOT FOUND THEN
        INSERT INTO public.solicitudes_autorizacion (
          fecha_solicitud, usuario_solicitante, rol_solicitante, modulo, tabla, formulario, registro_id, campo,
          valor_anterior, valor_nuevo, tipo_accion, motivo_solicitud, estado_solicitud, aplicado,
          condominio_id, solicitante_auth, created_at, updated_at)
        VALUES (now(), r.nombre, r.rol, 'Residentes', r.t, 'Portal', r.id, k,
          v_actual, p_fields->>k, 'Edición', 'Actualizacion de contacto desde el portal', 'Sometido', false,
          r.condominio_id, v_uid, now(), now());
      END IF;
      n := n + 1;
    END LOOP;
  END LOOP;
  RETURN jsonb_build_object('cambios_sometidos', n,
    'mensaje', CASE WHEN n = 0 THEN 'No hubo cambios' ELSE 'Cambios enviados; quedan pendientes de aprobacion de la administracion' END);
END $function$
;

