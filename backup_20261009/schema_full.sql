CREATE OR REPLACE FUNCTION public.axi_gasto_actualizar(p_gasto_id bigint, p_cambios jsonb)
 RETURNS public.gastos
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_gasto public.gastos;
  v_condos bigint[];
  v_es_ceo boolean;
  v_afecta_fc boolean;
  v_campo text;
  v_sensibles text[] := ARRAY['monto'];
BEGIN
  v_es_ceo := private.es_ceo();
  IF v_es_ceo THEN
    v_condos := private.staff_condos('Gastos', 'editar');
  ELSE
    IF EXISTS (SELECT 1 FROM public.permisos WHERE rol = 'Asistente' AND modulo = 'Gastos'
               AND requiere_autorizacion AND activo) THEN
      SELECT * INTO v_gasto FROM public.gastos g WHERE g.id = p_gasto_id;
      IF NOT FOUND THEN RAISE EXCEPTION 'Gasto % no existe', p_gasto_id; END IF;

      FOR v_campo IN SELECT * FROM jsonb_object_keys(p_cambios) LOOP
        IF v_campo = ANY(v_sensibles) THEN
          INSERT INTO public.solicitudes_autorizacion (
            modulo, tabla, registro_id, campo,
            valor_anterior, valor_nuevo, motivo_solicitud,
            usuario_solicitante_id, usuario_solicitante,
            estado_solicitud, tipo_accion, created_at
          ) VALUES (
            'Gastos', 'gastos', p_gasto_id, v_campo,
            to_jsonb(v_gasto) ->> v_campo, p_cambios ->> v_campo,
            'Edición requiere autorización CEO',
            private.mi_usuario_id(),
            (SELECT u.nombre_completo FROM public.usuarios u WHERE u.id = private.mi_usuario_id()),
            'Pendiente', 'Edición', now()
          );
        END IF;
      END LOOP;

      RAISE EXCEPTION 'Se crearon solicitudes de autorización para los campos sensibles. Espere aprobación del CEO.';
    ELSE
      v_condos := private.staff_condos('Gastos', 'editar');
    END IF;
  END IF;

  SELECT * INTO v_gasto FROM public.gastos g WHERE g.id = p_gasto_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Gasto % no existe', p_gasto_id; END IF;

  IF NOT (v_gasto.condominio_id = ANY(v_condos)) THEN
    RAISE EXCEPTION 'No tiene permiso en este condominio';
  END IF;

  v_afecta_fc := CASE
    WHEN p_cambios ? 'tipo_aplicacion' THEN
      lower(coalesce(p_cambios->>'tipo_aplicacion', '')) ILIKE 'com_n'
    ELSE v_gasto.afecta_fondo_comun
  END;

  UPDATE public.gastos SET
    proveedor_id = coalesce((p_cambios->>'proveedor_id')::bigint, proveedor_id),
    area_aplicacion = coalesce(p_cambios->>'area_aplicacion', area_aplicacion),
    area_aplicacion_otro = CASE
      WHEN lower(coalesce(p_cambios->>'area_aplicacion', area_aplicacion)) = 'otro'
        THEN coalesce(p_cambios->>'area_aplicacion_otro', area_aplicacion_otro)
      ELSE NULL END,
    tipo_aplicacion = coalesce(p_cambios->>'tipo_aplicacion', tipo_aplicacion),
    fecha = coalesce((p_cambios->>'fecha')::date, fecha),
    categoria = coalesce(p_cambios->>'categoria', categoria),
    descripcion = coalesce(p_cambios->>'descripcion', descripcion),
    monto = coalesce((p_cambios->>'monto')::numeric, monto),
    factura_proveedor = coalesce(p_cambios->>'factura_proveedor', factura_proveedor),
    metodo_pago = coalesce(p_cambios->>'metodo_pago', metodo_pago),
    foto_factura_url = coalesce(p_cambios->>'foto_factura_url', foto_factura_url),
    afecta_fondo_comun = v_afecta_fc,
    updated_at = now(),
    updated_by = (SELECT auth.uid())::text
  WHERE id = p_gasto_id
  RETURNING * INTO v_gasto;

  UPDATE public.facturas_gastos SET
    monto = v_gasto.monto,
    fecha = v_gasto.fecha,
    periodo = to_char(v_gasto.fecha, 'YYYY-MM'),
    categoria = v_gasto.categoria,
    concepto = v_gasto.descripcion,
    tipo_aplicacion = v_gasto.tipo_aplicacion,
    area_aplicacion = v_gasto.area_aplicacion,
    updated_at = now()
  WHERE gasto_id = p_gasto_id;

  PERFORM public.axi_libro_registrar_gasto(p_gasto_id);

  PERFORM private.log_portal('Gastos', 'gastos', p_gasto_id,
    NULL, NULL, NULL, 'Modificación',
    'Gasto actualizado: ' || v_gasto.codigo);

  RETURN v_gasto;
END $function$
;

CREATE OR REPLACE FUNCTION public.axi_gasto_eliminar(p_gasto_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_gasto public.gastos;
  v_condos bigint[];
BEGIN
  -- Solo CEO puede eliminar
  IF NOT private.es_ceo() THEN
    RAISE EXCEPTION 'Solo el CEO puede eliminar gastos';
  END IF;

  v_condos := private.staff_condos('Gastos', 'eliminar');

  SELECT * INTO v_gasto FROM public.gastos g WHERE g.id = p_gasto_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Gasto % no existe', p_gasto_id; END IF;

  IF NOT (v_gasto.condominio_id = ANY(v_condos)) THEN
    RAISE EXCEPTION 'No tiene permiso en este condominio';
  END IF;

  -- Marcar factura de gasto como eliminada (en vez de DELETE)
  UPDATE public.facturas_gastos SET
    estado = 'Eliminado',
    observaciones = '[ELIMINADO] ' || coalesce(observaciones, ''),
    updated_at = now()
  WHERE gasto_id = p_gasto_id;

  -- Anular asiento del libro (en vez de DELETE, zerear como audit trail)
  UPDATE public.libro_financiero SET
    entrada = 0, salida = 0, balance_movimiento = 0,
    concepto = '[ELIMINADO] ' || coalesce(concepto, ''),
    updated_at = now()
  WHERE gasto_id = p_gasto_id AND tipo_movimiento = 'Gasto operativo';

  -- Compatibilidad: también por código
  UPDATE public.libro_financiero SET
    entrada = 0, salida = 0, balance_movimiento = 0,
    concepto = '[ELIMINADO] ' || coalesce(concepto, ''),
    updated_at = now()
  WHERE codigo_pago = v_gasto.codigo AND tipo_movimiento = 'Gasto operativo'
    AND gasto_id IS NULL;

  -- Marcar el gasto como eliminado (en vez de DELETE)
  UPDATE public.gastos SET
    estado = 'Eliminado',
    updated_at = now(),
    updated_by = (SELECT auth.uid())::text
  WHERE id = p_gasto_id;

  -- Log
  PERFORM private.log_portal('Gastos', 'gastos', p_gasto_id,
    NULL, NULL, NULL, 'Eliminación',
    'Gasto eliminado: ' || coalesce(v_gasto.codigo, '?') || ' | Monto: ' || v_gasto.monto);
END $function$
;

