CREATE OR REPLACE FUNCTION public.fn_pago_postear_libro(p_pago_id bigint)
 RETURNS public.libro_financiero
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_pago public.pagos; v_factura public.facturas; v_entrada numeric(14,2); v_salida numeric(14,2); v_libro public.libro_financiero;
BEGIN
  SELECT * INTO v_pago FROM public.pagos p WHERE p.id = p_pago_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pago % no existe', p_pago_id; END IF;
  IF v_pago.estado_aprobacion <> 'Aprobado' THEN RETURN NULL; END IF;
  SELECT * INTO v_factura FROM public.facturas f WHERE f.id = v_pago.factura_id;
  CASE lower(v_pago.tipo_movimiento)
    WHEN 'ingreso recibido' THEN v_entrada := v_pago.monto; v_salida := 0;
    WHEN 'pago a suplidor'  THEN v_entrada := 0; v_salida := v_pago.monto;
    WHEN 'ajuste'           THEN v_entrada := v_pago.monto; v_salida := 0;
    WHEN 'anulación'        THEN v_entrada := 0; v_salida := v_pago.monto;
    ELSE v_entrada := v_pago.monto; v_salida := 0;
  END CASE;
  INSERT INTO public.libro_financiero (
    condominio_id, fecha, tipo_movimiento, tipo_aplicacion,
    unidad_id, propietario_id, inquilino_id, factura_id, pago_id,
    codigo_pago, concepto, entrada, salida, balance_movimiento,
    afecta_estado_cuenta, afecta_fondo_comun, created_by, created_at, updated_at
  ) VALUES (
    coalesce(v_pago.condominio_id, v_factura.condominio_id), v_pago.fecha_pago,
    v_pago.tipo_movimiento, coalesce(v_pago.tipo_aplicacion, v_factura.tipo_facturacion),
    coalesce(v_pago.unidad_id, v_factura.unidad_id), coalesce(v_pago.propietario_id, v_factura.propietario_id),
    v_pago.inquilino_id, v_pago.factura_id, v_pago.id, v_pago.codigo, v_pago.concepto,
    v_entrada, v_salida, v_entrada - v_salida,
    v_pago.afecta_estado_cuenta, v_pago.afecta_fondo_comun,
    (SELECT auth.uid())::text, now(), now()
