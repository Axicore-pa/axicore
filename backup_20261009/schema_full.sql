    tipo_aplicacion = EXCLUDED.tipo_aplicacion, unidad_id = EXCLUDED.unidad_id,
    propietario_id = EXCLUDED.propietario_id, inquilino_id = EXCLUDED.inquilino_id,
    factura_id = EXCLUDED.factura_id, codigo_pago = EXCLUDED.codigo_pago,
    concepto = EXCLUDED.concepto, entrada = EXCLUDED.entrada, salida = EXCLUDED.salida,
    balance_movimiento = EXCLUDED.balance_movimiento,
    afecta_estado_cuenta = EXCLUDED.afecta_estado_cuenta, afecta_fondo_comun = EXCLUDED.afecta_fondo_comun,
    updated_at = now()
  RETURNING * INTO v_libro;
