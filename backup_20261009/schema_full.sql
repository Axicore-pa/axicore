CREATE OR REPLACE FUNCTION public.fn_pago_registrar(p jsonb)
 RETURNS public.pagos
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_factura public.facturas; v_pago public.pagos; v_codigo text; v_condos bigint[];
  v_tipo_mov text; v_tipo_apl text; v_ec boolean; v_fc boolean; v_concepto text;
  v_pend numeric(14,2); v_disp numeric(14,2); v_ceo boolean := private.es_ceo(); v_monto numeric(14,2);
BEGIN
  v_condos := private.staff_condos('Pagos', 'crear');
  IF coalesce(cardinality(v_condos), 0) = 0 THEN RAISE EXCEPTION 'No tiene permiso para registrar pagos'; END IF;
  IF (p->>'factura_id') IS NULL THEN RAISE EXCEPTION 'Debe indicar la factura'; END IF;
  SELECT * INTO v_factura FROM public.facturas f WHERE f.id = (p->>'factura_id')::bigint;
  IF NOT FOUND THEN RAISE EXCEPTION 'Factura % no existe', p->>'factura_id'; END IF;
  IF NOT (v_factura.condominio_id = ANY (v_condos)) THEN RAISE EXCEPTION 'No tiene permiso en este condominio'; END IF;
  IF v_factura.estado_aprobacion <> 'Aprobado' THEN RAISE EXCEPTION 'La factura % aun no esta aprobada por el CEO', v_factura.no_factura; END IF;
  IF lower(v_factura.estado) NOT IN ('pendiente','parcial','vencida') THEN RAISE EXCEPTION 'La factura no admite pagos (estado: %)', v_factura.estado; END IF;

  v_monto := coalesce((p->>'monto')::numeric, 0);
  IF v_monto <= 0 THEN RAISE EXCEPTION 'El monto debe ser mayor que cero'; END IF;
  IF (p->>'fecha_pago') IS NULL THEN RAISE EXCEPTION 'Debe indicar la fecha de pago'; END IF;
  IF coalesce(p->>'metodo', '') NOT IN ('Efectivo','Transferencia','Depósito','Cheque','Tarjeta','Otro') THEN
    RAISE EXCEPTION 'Metodo de pago no valido'; END IF;
  IF p->>'metodo' = 'Transferencia' AND coalesce(p->>'banco', '') = '' THEN RAISE EXCEPTION 'Debe indicar el banco para transferencias'; END IF;
  IF coalesce(btrim(p->>'recibido_de'), '') = '' THEN RAISE EXCEPTION 'Debe indicar de quien se recibio el pago'; END IF;

  v_tipo_mov := coalesce(nullif(p->>'tipo_movimiento', ''), 'Ingreso recibido');
  IF v_tipo_mov NOT IN ('Ingreso recibido','Pago a suplidor','Ajuste','Anulación') THEN RAISE EXCEPTION 'Tipo de movimiento no valido'; END IF;
  v_tipo_apl := coalesce(nullif(p->>'tipo_aplicacion', ''),
                         CASE WHEN lower(coalesce(v_factura.tipo_facturacion, '')) = 'inquilino' THEN 'Inquilino' ELSE 'Propietario' END);
  IF v_tipo_apl NOT IN ('Propietario','Inquilino','Suplidor','Unidad','Área común') THEN RAISE EXCEPTION 'Tipo de aplicacion no valido'; END IF;

  CASE v_tipo_mov
    WHEN 'Ingreso recibido' THEN v_ec := true; v_fc := true;
    WHEN 'Pago a suplidor'  THEN v_ec := true; v_fc := (v_tipo_apl <> 'Unidad');
    ELSE v_ec := true; v_fc := false;
  END CASE;
  IF p ? 'afecta_estado_cuenta' THEN v_ec := coalesce((p->>'afecta_estado_cuenta')::boolean, v_ec); END IF;
  IF p ? 'afecta_fondo_comun'   THEN v_fc := coalesce((p->>'afecta_fondo_comun')::boolean, v_fc); END IF;
  IF lower(coalesce(v_factura.tipo_facturacion, '')) = 'inquilino' THEN v_fc := false; END IF;
  IF coalesce(v_factura.tipo_factura, '') ILIKE '%GLP%' OR coalesce(v_factura.tipo_facturacion, '') ILIKE '%GLP%'
     OR v_tipo_apl ILIKE '%GLP%' THEN v_fc := false; END IF;

  SELECT coalesce(sum(x.monto), 0) INTO v_pend FROM public.pagos x
   WHERE x.factura_id = v_factura.id AND x.estado_aprobacion IN ('Sometido','En proceso')
     AND coalesce(x.tipo_movimiento, 'Ingreso recibido') = 'Ingreso recibido'
     AND lower(coalesce(x.estado, '')) NOT IN ('anulado','anulada');
  v_disp := coalesce(v_factura.balance_pendiente, v_factura.monto) - v_pend;
  IF v_tipo_mov = 'Ingreso recibido' AND v_monto > v_disp AND NOT v_ceo THEN
    RAISE EXCEPTION 'El monto (%) excede el balance disponible (%) considerando pagos en aprobacion. Solo el CEO puede autorizar sobrepagos.', v_monto, v_disp;
  END IF;

  v_codigo := public.fn_pago_generar_codigo(v_factura.id, (p->>'fecha_pago')::date);
  v_concepto := coalesce(nullif(p->>'concepto', ''),
                v_tipo_mov || ' aplicado a factura ' || v_factura.no_factura || ' | ' || coalesce(v_factura.concepto, ''));

  INSERT INTO public.pagos (
    condominio_id, factura_id, unidad_id, propietario_id, inquilino_id,
    codigo, fecha_pago, monto, metodo, banco, referencia, recibido_de, recibido_por,
    estado, tipo_movimiento, tipo_aplicacion, afecta_estado_cuenta, afecta_fondo_comun,
    validado, fecha_validacion, concepto, observaciones, created_at, updated_at
  ) VALUES (
    v_factura.condominio_id, v_factura.id, v_factura.unidad_id, v_factura.propietario_id,
    CASE WHEN lower(coalesce(v_factura.tipo_facturacion, '')) = 'inquilino' THEN v_factura.inquilino_id END,
    v_codigo, (p->>'fecha_pago')::date, v_monto, p->>'metodo',
    CASE WHEN p->>'metodo' = 'Transferencia' THEN p->>'banco' ELSE nullif(p->>'banco', '') END,
    nullif(p->>'referencia', ''), btrim(p->>'recibido_de'),
    (SELECT u.nombre_completo FROM public.usuarios u WHERE u.id = private.mi_usuario_id()),
    CASE WHEN v_tipo_mov = 'Ingreso recibido' THEN 'Pendiente' ELSE v_tipo_mov END,
    v_tipo_mov, v_tipo_apl, v_ec, v_fc,
    v_ceo, CASE WHEN v_ceo THEN private.hoy() END,
    v_concepto, nullif(p->>'observaciones', ''), now(), now()
  ) RETURNING * INTO v_pago;

  IF v_pago.estado_aprobacion = 'Aprobado' THEN
    PERFORM public.fn_pago_postear_libro(v_pago.id);
    IF v_tipo_mov = 'Ingreso recibido' THEN
      UPDATE public.pagos SET estado = (SELECT f.estado FROM public.facturas f WHERE f.id = v_factura.id)
       WHERE id = v_pago.id RETURNING * INTO v_pago;
    END IF;
  END IF;

  PERFORM private.log_portal('Pagos', 'pagos', v_pago.id, NULL, NULL, v_codigo, 'Creación',
    'Pago ' || lower(v_pago.estado_aprobacion) || ': ' || v_codigo || ' | Monto: ' || v_pago.monto || ' | Factura: ' || v_factura.no_factura);
  RETURN v_pago;
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_proveedor_solicitar_cambio(p_proveedor_id bigint, p_cambios jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v jsonb; k text; n int := 0;
  v_permitidos text[] := ARRAY['nombre','nombre_comercial','rnc_cedula','servicio','tipo_proveedor','tipo_proveedor_otro',
    'telefono','email','contacto','calle_numero','sector','sector_otro','municipio','ciudad','codigo_postal',
    'condicion_pago','terminos_pago','metodo_pago','banco','tipo_cuenta','cuenta_bancaria','titular_cuenta','notas','activo'];
BEGIN
  IF NOT private.es_staff() THEN RAISE EXCEPTION 'Sin permiso' USING ERRCODE = '42501'; END IF;
  SELECT to_jsonb(p) INTO v FROM public.proveedores p WHERE p.id = p_proveedor_id;
  IF v IS NULL THEN RAISE EXCEPTION 'Proveedor no encontrado'; END IF;
  FOR k IN SELECT jsonb_object_keys(p_cambios) LOOP
    CONTINUE WHEN NOT (k = ANY (v_permitidos)) OR NOT (v ? k);
    CONTINUE WHEN (v->>k) IS NOT DISTINCT FROM (p_cambios->>k);
    IF private.es_ceo() THEN
      EXECUTE format('UPDATE public.proveedores SET %I = %L, updated_at = now() WHERE id = $1', k, p_cambios->>k) USING p_proveedor_id;
    ELSE
      INSERT INTO public.solicitudes_autorizacion (fecha_solicitud, usuario_solicitante_id, usuario_solicitante, rol_solicitante,
        modulo, tabla, formulario, registro_id, campo, valor_anterior, valor_nuevo, tipo_accion, motivo_solicitud,
        estado_solicitud, aplicado, solicitante_auth, created_at, updated_at)
      VALUES (now(), private.mi_usuario_id(), private.nombre_auth((SELECT auth.uid())), 'Asistente',
        'Proveedores', 'proveedores', 'Web', p_proveedor_id, k, v->>k, p_cambios->>k, 'Edición', 'Cambio de proveedor',
        'Sometido', false, (SELECT auth.uid()), now(), now());
    END IF;
    n := n + 1;
  END LOOP;
  RETURN jsonb_build_object('cambios', n, 'aplicados_directo', private.es_ceo());
END $function$
;

