CREATE OR REPLACE FUNCTION public.fn_pago_anular(p_pago_id bigint, p_motivo text DEFAULT NULL::text)
 RETURNS public.pagos
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v_pago public.pagos; v_condos bigint[];
BEGIN
  v_condos := private.staff_condos('Pagos', 'eliminar');
  SELECT * INTO v_pago FROM public.pagos p WHERE p.id = p_pago_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pago % no existe', p_pago_id; END IF;
  IF NOT (v_pago.condominio_id = ANY(v_condos)) THEN RAISE EXCEPTION 'No tiene permiso para anular pagos en este condominio'; END IF;
  IF lower(coalesce(v_pago.estado, '')) IN ('anulado', 'anulada') THEN RAISE EXCEPTION 'El pago ya está anulado'; END IF;
  UPDATE public.pagos SET estado = 'Anulado',
    observaciones = coalesce(observaciones || E'\n', '') || '[ANULADO ' || to_char(now(), 'YYYY-MM-DD HH24:MI') || '] ' || coalesce(p_motivo, ''),
    updated_at = now()
  WHERE id = p_pago_id RETURNING * INTO v_pago;
  -- Contraasiento en libro y borrar asiento original
  INSERT INTO public.libro_financiero (
    condominio_id, fecha, tipo_movimiento, tipo_aplicacion, unidad_id, propietario_id, inquilino_id,
    factura_id, pago_id, codigo_pago, concepto, entrada, salida, balance_movimiento,
    afecta_estado_cuenta, afecta_fondo_comun, created_by, created_at
  ) SELECT lf.condominio_id, (now() AT TIME ZONE 'America/Santo_Domingo')::date, 'Anulación de pago', lf.tipo_aplicacion,
    lf.unidad_id, lf.propietario_id, lf.inquilino_id, lf.factura_id, NULL, lf.codigo_pago || '-ANUL',
    'ANULACIÓN: ' || coalesce(lf.concepto, ''), lf.salida, lf.entrada, lf.salida - lf.entrada,
    lf.afecta_estado_cuenta, lf.afecta_fondo_comun, (SELECT auth.uid())::text, now()
  FROM public.libro_financiero lf WHERE lf.pago_id = p_pago_id;
  -- Marcar asiento original como nulo en lugar de borrarlo
  UPDATE public.libro_financiero SET entrada = 0, salida = 0, balance_movimiento = 0,
    concepto = '[ANULADO] ' || coalesce(concepto, ''), updated_at = now()
  WHERE pago_id = p_pago_id;
  PERFORM private.log_portal('Pagos', 'pagos', p_pago_id, 'estado', 'Activo', 'Anulado', 'Anulación',
    'Pago anulado: ' || v_pago.codigo || coalesce(' | Motivo: ' || p_motivo, ''));
  RETURN v_pago;
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_pago_editar(p_pago_id bigint, p_cambios jsonb, p_motivo text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_pago public.pagos; v_campo text; v_valor text; v_anterior text;
  v_es_ceo boolean := private.es_ceo(); v_aplicados int := 0; v_solic int := 0; v_uid uuid := (SELECT auth.uid());
  v_permitidos text[] := ARRAY['fecha_pago','monto','metodo','banco','referencia','recibido_de',
    'tipo_movimiento','tipo_aplicacion','afecta_estado_cuenta','afecta_fondo_comun','concepto','observaciones'];
  v_requiere_recalc boolean := false;
BEGIN
  SELECT * INTO v_pago FROM public.pagos p WHERE p.id = p_pago_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pago % no existe', p_pago_id; END IF;
  IF NOT (v_es_ceo OR v_pago.condominio_id = ANY (private.staff_condos('Pagos','ver'))) THEN
    RAISE EXCEPTION 'Sin permiso para editar este pago' USING ERRCODE='42501'; END IF;
  IF v_pago.estado_aprobacion <> 'Aprobado' THEN RAISE EXCEPTION 'Solo se edita un pago Aprobado (estado actual: %)', v_pago.estado_aprobacion; END IF;

  FOR v_campo, v_valor IN SELECT * FROM jsonb_each_text(p_cambios) LOOP
    CONTINUE WHEN NOT (v_campo = ANY (v_permitidos));
    v_anterior := to_jsonb(v_pago) ->> v_campo;
    CONTINUE WHEN v_anterior IS NOT DISTINCT FROM v_valor;
    IF v_es_ceo THEN
      EXECUTE format('UPDATE public.pagos SET %I = %L, updated_at = now() WHERE id = $1', v_campo, v_valor) USING p_pago_id;
      IF v_campo IN ('monto','tipo_movimiento','afecta_estado_cuenta','afecta_fondo_comun','tipo_aplicacion') THEN v_requiere_recalc := true; END IF;
      PERFORM private.log_portal('Pagos','pagos',p_pago_id,v_campo,v_anterior,v_valor,'Modificación','Edicion de pago');
      v_aplicados := v_aplicados + 1;
    ELSE
      INSERT INTO public.solicitudes_autorizacion (fecha_solicitud, usuario_solicitante_id, usuario_solicitante, rol_solicitante,
        modulo, tabla, formulario, registro_id, campo, valor_anterior, valor_nuevo, tipo_accion, motivo_solicitud,
        estado_solicitud, aplicado, condominio_id, solicitante_auth, created_at, updated_at)
      VALUES (now(), private.mi_usuario_id(), private.nombre_auth(v_uid), 'Asistente',
        'Pagos', 'pagos', 'Web', p_pago_id, v_campo, v_anterior, v_valor, 'Edición', coalesce(p_motivo,'Edicion de pago'),
        'Sometido', false, v_pago.condominio_id, v_uid, now(), now());
      v_solic := v_solic + 1;
    END IF;
  END LOOP;

  IF v_es_ceo AND v_requiere_recalc THEN
    PERFORM public.fn_pago_postear_libro(p_pago_id);
    PERFORM public.fn_factura_recalcular(v_pago.factura_id);
  END IF;
  RETURN jsonb_build_object('aplicados', v_aplicados, 'sometidos', v_solic, 'es_ceo', v_es_ceo);
END $function$
;

