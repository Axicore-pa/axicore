CREATE OR REPLACE FUNCTION public.fn_solicitar_anulacion(p_tabla text, p_id bigint, p_motivo text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v_condo bigint; v_ref text; v_mod text; v_id bigint;
BEGIN
  IF NOT private.es_staff() THEN RAISE EXCEPTION 'Sin permiso' USING ERRCODE = '42501'; END IF;
  IF nullif(btrim(p_motivo), '') IS NULL THEN RAISE EXCEPTION 'Indique el motivo de la anulacion'; END IF;
  CASE p_tabla
    WHEN 'facturas' THEN SELECT condominio_id, no_factura INTO v_condo, v_ref FROM public.facturas WHERE id = p_id; v_mod := 'Facturacion';
    WHEN 'pagos'    THEN SELECT condominio_id, codigo     INTO v_condo, v_ref FROM public.pagos    WHERE id = p_id; v_mod := 'Pagos';
    WHEN 'gastos'   THEN SELECT condominio_id, codigo     INTO v_condo, v_ref FROM public.gastos   WHERE id = p_id; v_mod := 'Gastos';
    ELSE RAISE EXCEPTION 'Tipo de registro no valido';
  END CASE;
  IF v_condo IS NULL THEN RAISE EXCEPTION 'Registro no encontrado'; END IF;
  IF NOT (private.es_ceo() OR v_condo = ANY (private.staff_condos(v_mod, 'ver'))) THEN RAISE EXCEPTION 'Sin permiso en este condominio' USING ERRCODE = '42501'; END IF;
  IF EXISTS (SELECT 1 FROM public.solicitudes_autorizacion s WHERE s.tabla = p_tabla AND s.registro_id = p_id
               AND s.tipo_accion = 'Anulación' AND s.estado_solicitud IN ('Pendiente','Sometido','En proceso')) THEN
    RAISE EXCEPTION 'Ya existe una solicitud de anulacion abierta para %', v_ref; END IF;
  INSERT INTO public.solicitudes_autorizacion (fecha_solicitud, usuario_solicitante_id, usuario_solicitante, rol_solicitante,
    modulo, tabla, formulario, registro_id, campo, valor_anterior, valor_nuevo, tipo_accion, motivo_solicitud,
    estado_solicitud, aplicado, condominio_id, solicitante_auth, created_at, updated_at)
  VALUES (now(), private.mi_usuario_id(), private.nombre_auth((SELECT auth.uid())), 'Asistente',
    v_mod, p_tabla, 'Web', p_id, 'estado', NULL, 'Anulado', 'Anulación', btrim(p_motivo),
    'Sometido', false, v_condo, (SELECT auth.uid()), now(), now())
  RETURNING id INTO v_id;
  RETURN v_id;
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_solicitud_aprobar(p_id bigint, p_comentario text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v_sol record;
BEGIN
  IF NOT private.es_ceo() THEN RAISE EXCEPTION 'Solo el CEO puede aprobar solicitudes'; END IF;
  SELECT * INTO v_sol FROM public.solicitudes_autorizacion WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Solicitud % no existe', p_id; END IF;
  IF v_sol.estado_solicitud <> 'Pendiente' THEN RAISE EXCEPTION 'La solicitud ya fue procesada (estado: %)', v_sol.estado_solicitud; END IF;
  DECLARE v_actual text;
  BEGIN
    EXECUTE format('SELECT (%I)::text FROM public.%I WHERE id = $1', v_sol.campo, v_sol.tabla) INTO v_actual USING v_sol.registro_id;
    IF v_actual IS DISTINCT FROM v_sol.valor_anterior THEN RAISE EXCEPTION 'El valor actual (%) ya no coincide con el anterior (%). Alguien lo cambió.', v_actual, v_sol.valor_anterior; END IF;
  END;
  EXECUTE format('UPDATE public.%I SET %I = $1, updated_at = now() WHERE id = $2', v_sol.tabla, v_sol.campo) USING v_sol.valor_nuevo, v_sol.registro_id;
  UPDATE public.solicitudes_autorizacion SET
    estado_solicitud = 'Aprobada', autorizado_por_usuario_id = private.mi_usuario_id(),
    autorizado_por_nombre = (SELECT u.nombre_completo FROM public.usuarios u WHERE u.id = private.mi_usuario_id()),
    comentario_ceo = p_comentario, fecha_autorizacion = now(), aplicado = true, fecha_aplicacion = now()
  WHERE id = p_id;
  IF v_sol.tabla = 'pagos' AND v_sol.campo IN ('monto', 'factura_id') THEN
    PERFORM public.fn_pago_postear_libro(v_sol.registro_id);
    DECLARE v_fid bigint;
    BEGIN SELECT factura_id INTO v_fid FROM public.pagos WHERE id = v_sol.registro_id; PERFORM public.fn_factura_recalcular(v_fid); END;
  END IF;
  PERFORM private.log_portal(v_sol.modulo, v_sol.tabla, v_sol.registro_id, v_sol.campo, v_sol.valor_anterior, v_sol.valor_nuevo, 'Autorización',
    'Solicitud aprobada: ' || v_sol.campo || ' -> ' || v_sol.valor_nuevo || coalesce(' | ' || p_comentario, ''));
END $function$
;

