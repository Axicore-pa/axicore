CREATE OR REPLACE FUNCTION public.fn_factura_aplicar_recurrencia(p_factura_id bigint, p_modo text, p_dia integer DEFAULT NULL::integer, p_meses integer DEFAULT NULL::integer)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_factura public.facturas;
  v_count int := 0;
  v_i int;
  v_fecha_nueva date;
  v_periodo_nuevo text;
  v_no_factura text;
  v_new_id bigint;
BEGIN
  SELECT * INTO v_factura FROM public.facturas f WHERE f.id = p_factura_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Factura % no existe', p_factura_id;
  END IF;

  IF lower(v_factura.estado) = 'anulada' THEN
    RAISE EXCEPTION 'No se puede aplicar recurrencia a una factura anulada';
  END IF;

  UPDATE public.facturas SET
    es_recurrente = true,
    tipo_recurrencia = CASE WHEN lower(p_modo) = 'indefinida' THEN 'Mensual indefinida' ELSE 'Mensual por cantidad' END,
    dia_recurrencia = p_dia,
    cantidad_meses_recurrencia = p_meses,
    recurrencia_indefinida = (lower(p_modo) = 'indefinida'),
    updated_at = now()
  WHERE id = p_factura_id;

  IF lower(p_modo) = 'indefinida' THEN
    RETURN 0;
  END IF;

  IF p_meses IS NULL OR p_meses <= 0 THEN
    RAISE EXCEPTION 'Debe indicar la cantidad de meses';
  END IF;

  FOR v_i IN 1..p_meses LOOP
    v_fecha_nueva := v_factura.fecha_factura + (v_i || ' months')::interval;
    IF p_dia IS NOT NULL THEN
      v_fecha_nueva := make_date(extract(year FROM v_fecha_nueva)::int,
                                  extract(month FROM v_fecha_nueva)::int,
                                  least(p_dia, (date_trunc('month', v_fecha_nueva) + interval '1 month - 1 day')::date - date_trunc('month', v_fecha_nueva)::date + 1));
    END IF;
    v_periodo_nuevo := to_char(v_fecha_nueva, 'YYYY-MM');

    IF EXISTS (
      SELECT 1 FROM public.facturas
       WHERE factura_origen_id = p_factura_id
         AND periodo = v_periodo_nuevo
         AND lower(estado) <> 'anulada'
    ) THEN
      CONTINUE;
    END IF;

    v_no_factura := public.fn_factura_siguiente_numero(v_factura.condominio_id);

    INSERT INTO public.facturas (
      condominio_id, no_factura, unidad_id, propietario_id, inquilino_id,
      tipo_facturacion, tipo_factura, periodo, fecha_factura, fecha_vencimiento,
      concepto, monto, monto_pagado, balance_pendiente, estado,
      factura_origen_id, created_at, updated_at
    ) VALUES (
      v_factura.condominio_id, v_no_factura, v_factura.unidad_id, v_factura.propietario_id, v_factura.inquilino_id,
      v_factura.tipo_facturacion, v_factura.tipo_factura, v_periodo_nuevo, v_fecha_nueva,
      CASE WHEN v_factura.fecha_vencimiento IS NOT NULL
        THEN v_fecha_nueva + (v_factura.fecha_vencimiento - v_factura.fecha_factura)
        ELSE NULL END,
      v_factura.concepto, v_factura.monto, 0, v_factura.monto, 'Pendiente',
      p_factura_id, now(), now()
    );

    v_count := v_count + 1;
  END LOOP;

  RETURN v_count;
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_factura_crear_individual(p_unidad_id bigint, p_tipo_facturacion text DEFAULT 'Propietario'::text, p_inquilino_id bigint DEFAULT NULL::bigint, p_tipo_factura text DEFAULT 'Mantenimiento'::text, p_fecha_factura date DEFAULT NULL::date, p_fecha_vencimiento date DEFAULT NULL::date, p_periodo text DEFAULT NULL::text, p_concepto text DEFAULT NULL::text, p_monto numeric DEFAULT NULL::numeric)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_unidad public.unidades;
  v_condominio_id bigint;
  v_propietario_id bigint;
  v_inquilino_id bigint;
  v_monto numeric(14,2);
  v_fecha date;
  v_fecha_venc date;
  v_periodo text;
  v_concepto text;
  v_no_factura text;
  v_factura_id bigint;
  v_condos bigint[];
BEGIN
  v_condos := private.staff_condos('Facturación', 'crear');
  IF array_length(v_condos, 1) IS NULL OR v_condos = '{}' THEN
    RAISE EXCEPTION 'No tiene permiso para crear facturas';
  END IF;

  IF p_unidad_id IS NULL THEN
    RAISE EXCEPTION 'Debe seleccionar una unidad';
  END IF;

  SELECT * INTO v_unidad FROM public.unidades u WHERE u.id = p_unidad_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Unidad % no existe', p_unidad_id;
  END IF;

  v_condominio_id := v_unidad.condominio_id;

  IF NOT (v_condominio_id = ANY(v_condos)) THEN
    RAISE EXCEPTION 'No tiene permiso en este condominio';
  END IF;

  v_propietario_id := v_unidad.propietario_id;

  IF lower(coalesce(p_tipo_facturacion, 'Propietario')) = 'inquilino' THEN
    IF p_inquilino_id IS NULL THEN
      RAISE EXCEPTION 'Debe seleccionar un inquilino para facturación tipo Inquilino';
    END IF;
    v_inquilino_id := p_inquilino_id;
    IF NOT EXISTS (SELECT 1 FROM public.inquilinos i WHERE i.id = v_inquilino_id AND i.condominio_id = v_condominio_id) THEN
      RAISE EXCEPTION 'Inquilino % no pertenece al condominio', v_inquilino_id;
    END IF;
  ELSE
    v_inquilino_id := NULL;
  END IF;

  v_fecha := coalesce(p_fecha_factura, (now() AT TIME ZONE 'America/Santo_Domingo')::date);
  v_fecha_venc := p_fecha_vencimiento;
  v_periodo := coalesce(p_periodo, to_char(v_fecha, 'YYYY-MM'));
  v_monto := coalesce(p_monto, v_unidad.cuota_mantenimiento);
  IF v_monto IS NULL OR v_monto <= 0 THEN
    RAISE EXCEPTION 'El monto debe ser mayor que cero';
  END IF;

  v_concepto := coalesce(nullif(trim(p_concepto), ''), coalesce(p_tipo_factura, 'Mantenimiento'));
  v_no_factura := public.fn_factura_siguiente_numero(v_condominio_id);

  INSERT INTO public.facturas (
    condominio_id, no_factura, unidad_id, propietario_id, inquilino_id,
    tipo_facturacion, tipo_factura, periodo, fecha_factura, fecha_vencimiento,
    concepto, monto, monto_pagado, balance_pendiente, estado,
    created_at, updated_at
  ) VALUES (
    v_condominio_id, v_no_factura, p_unidad_id, v_propietario_id, v_inquilino_id,
    coalesce(p_tipo_facturacion, 'Propietario'), coalesce(p_tipo_factura, 'Mantenimiento'),
    v_periodo, v_fecha, v_fecha_venc,
    v_concepto, v_monto, 0, v_monto, 'Pendiente',
    now(), now()
  ) RETURNING id INTO v_factura_id;

  PERFORM private.log_portal('Facturación', 'facturas', v_factura_id,
    NULL, NULL, v_no_factura, 'Creación',
    'Factura individual creada: ' || v_no_factura || ' | Monto: ' || v_monto);

  RETURN v_factura_id;
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_factura_recalcular(p_factura_id bigint)
 RETURNS public.facturas
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_factura public.facturas; v_pagado numeric(14,2); v_balance numeric(14,2); v_estado text; v_hoy date;
BEGIN
  SELECT * INTO v_factura FROM public.facturas f WHERE f.id = p_factura_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Factura % no existe', p_factura_id; END IF;
  IF lower(v_factura.estado) = 'anulada' THEN RETURN v_factura; END IF;
  v_hoy := (now() AT TIME ZONE 'America/Santo_Domingo')::date;
  SELECT coalesce(sum(p.monto), 0) INTO v_pagado
    FROM public.pagos p
   WHERE p.factura_id = p_factura_id
     AND p.estado_aprobacion = 'Aprobado'
     AND coalesce(p.tipo_movimiento, 'Ingreso recibido') = 'Ingreso recibido'
     AND lower(coalesce(p.estado, '')) NOT IN ('anulado', 'anulada');
  v_balance := greatest(v_factura.monto - v_pagado, 0);
  IF v_balance = 0 THEN v_estado := 'Pagada';
  ELSIF v_pagado > 0 THEN v_estado := 'Parcial';
  ELSIF v_factura.fecha_vencimiento IS NOT NULL AND v_factura.fecha_vencimiento < v_hoy THEN v_estado := 'Vencida';
  ELSE v_estado := 'Pendiente';
  END IF;
  UPDATE public.facturas SET monto_pagado = v_pagado, balance_pendiente = v_balance, estado = v_estado, updated_at = now()
   WHERE id = p_factura_id RETURNING * INTO v_factura;
  RETURN v_factura;
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_factura_siguiente_numero(p_condominio_id bigint)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_prefijo text;
  v_max_seq int;
  v_numero text;
BEGIN
  SELECT coalesce(c.codigo, 'COND' || c.id)
    INTO v_prefijo
    FROM public.condominios c WHERE c.id = p_condominio_id;
  IF v_prefijo IS NULL THEN
    RAISE EXCEPTION 'Condominio % no existe', p_condominio_id;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('factura_num_' || p_condominio_id::text));
  SELECT coalesce(max(
    nullif(regexp_replace(f.no_factura, '^.*FAC-0*', ''), '')::int
  ), 0)
    INTO v_max_seq
    FROM public.facturas f
   WHERE f.condominio_id = p_condominio_id
     AND f.no_factura ~ ('^' || v_prefijo || '-FAC-[0-9]+$');
  v_numero := v_prefijo || '-FAC-' || lpad((v_max_seq + 1)::text, 5, '0');
  WHILE EXISTS (SELECT 1 FROM public.facturas WHERE condominio_id = p_condominio_id AND no_factura = v_numero) LOOP
    v_max_seq := v_max_seq + 1;
    v_numero := v_prefijo || '-FAC-' || lpad((v_max_seq + 1)::text, 5, '0');
  END LOOP;
  RETURN v_numero;
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_facturacion_mensual_generar(p_condominio_id bigint, p_periodo text, p_fecha_factura date, p_fecha_vencimiento date, p_concepto text, p_aceptar_fechas_no_estandar boolean DEFAULT false)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_candidato record;
  v_no_factura text;
  v_factura_id bigint;
  v_creadas int := 0;
  v_omitidas int := 0;
  v_concepto_linea text;
  v_condos bigint[];
  v_sug record;
BEGIN
  v_condos := private.staff_condos('Facturación', 'crear');
  IF NOT (p_condominio_id = ANY(v_condos)) THEN
    RAISE EXCEPTION 'No tiene permiso para facturar en este condominio';
  END IF;

  IF NOT p_aceptar_fechas_no_estandar THEN
    SELECT * INTO v_sug FROM public.fn_facturacion_mensual_sugerencias(p_periodo);
    IF p_fecha_factura <> v_sug.fecha_factura OR p_fecha_vencimiento <> v_sug.fecha_vencimiento THEN
      RETURN jsonb_build_object(
        'error', 'Las fechas no coinciden con las sugeridas. Use p_aceptar_fechas_no_estandar = true para forzar.',
        'sugerida_factura', v_sug.fecha_factura,
        'sugerida_vencimiento', v_sug.fecha_vencimiento
      );
    END IF;
  END IF;

  FOR v_candidato IN
    SELECT * FROM public.fn_facturacion_mensual_preview(p_condominio_id, p_periodo)
     WHERE NOT ya_facturada AND monto_calculado > 0
  LOOP
    v_no_factura := public.fn_factura_siguiente_numero(p_condominio_id);

    v_concepto_linea := coalesce(p_concepto, 'Cuota de mantenimiento')
      || ' | Unidad ' || v_candidato.unidad_codigo;
    IF v_candidato.prorrateada THEN
      v_concepto_linea := v_concepto_linea || ' | Prorrateada';
    END IF;

    INSERT INTO public.facturas (
      condominio_id, no_factura, unidad_id, propietario_id,
      tipo_facturacion, tipo_factura, periodo, fecha_factura, fecha_vencimiento,
      concepto, subtotal, monto, monto_pagado, balance_pendiente, estado,
      emitida, created_at, updated_at
    ) VALUES (
      p_condominio_id, v_no_factura, v_candidato.unidad_id, v_candidato.propietario_id,
      'Propietario', 'Mantenimiento', p_periodo, p_fecha_factura, p_fecha_vencimiento,
      v_concepto_linea, v_candidato.monto_calculado, v_candidato.monto_calculado,
      0, v_candidato.monto_calculado, 'Pendiente',
      true, now(), now()
    );

    v_creadas := v_creadas + 1;
  END LOOP;

  FOR v_candidato IN
    SELECT f.* FROM public.facturas f
     WHERE f.condominio_id = p_condominio_id
       AND f.recurrencia_indefinida = true
       AND f.es_recurrente = true
       AND lower(f.estado) <> 'anulada'
       AND NOT EXISTS (
         SELECT 1 FROM public.facturas f2
          WHERE f2.factura_origen_id = f.id
            AND f2.periodo = p_periodo
            AND lower(f2.estado) <> 'anulada'
       )
       AND NOT EXISTS (
         SELECT 1 FROM public.facturas f3
          WHERE f3.unidad_id = f.unidad_id
            AND f3.periodo = p_periodo
            AND lower(f3.tipo_factura) IN ('mantenimiento','administracion','administración','mantenimiento mensual')
            AND lower(f3.estado) <> 'anulada'
       )
  LOOP
    v_no_factura := public.fn_factura_siguiente_numero(p_condominio_id);

    INSERT INTO public.facturas (
      condominio_id, no_factura, unidad_id, propietario_id, inquilino_id,
      tipo_facturacion, tipo_factura, periodo, fecha_factura, fecha_vencimiento,
      concepto, monto, monto_pagado, balance_pendiente, estado,
      factura_origen_id, created_at, updated_at
    ) VALUES (
      v_candidato.condominio_id, v_no_factura, v_candidato.unidad_id, v_candidato.propietario_id, v_candidato.inquilino_id,
      v_candidato.tipo_facturacion, v_candidato.tipo_factura, p_periodo, p_fecha_factura, p_fecha_vencimiento,
      v_candidato.concepto, v_candidato.monto, 0, v_candidato.monto, 'Pendiente',
      v_candidato.id, now(), now()
    );

    v_creadas := v_creadas + 1;
  END LOOP;

  SELECT count(*) INTO v_omitidas
    FROM public.fn_facturacion_mensual_preview(p_condominio_id, p_periodo)
   WHERE ya_facturada;

  RETURN jsonb_build_object(
    'creadas', v_creadas,
    'omitidas_duplicadas', v_omitidas,
    'periodo', p_periodo,
    'condominio_id', p_condominio_id
  );
END $function$
;

CREATE OR REPLACE FUNCTION public.fn_facturacion_mensual_preview(p_condominio_id bigint, p_periodo text)
 RETURNS TABLE(unidad_id bigint, unidad_codigo text, propietario_id bigint, propietario_nombre text, cuota numeric, prorrateada boolean, monto_calculado numeric, ya_facturada boolean)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_anio int;
  v_mes int;
  v_inicio date;
  v_fin date;
  v_dias_periodo int;
BEGIN
  v_anio := split_part(p_periodo, '-', 1)::int;
  v_mes := split_part(p_periodo, '-', 2)::int;

  v_inicio := make_date(v_anio, v_mes, 1);
  IF v_mes = 2 THEN
    v_fin := make_date(v_anio, 2, 28);
  ELSE
    v_fin := (date_trunc('month', v_inicio) + interval '1 month - 1 day')::date;
  END IF;
  v_dias_periodo := v_fin - v_inicio + 1;

  RETURN QUERY
  SELECT
    u.id AS unidad_id,
    u.codigo AS unidad_codigo,
    u.propietario_id,
    p.nombre AS propietario_nombre,
    u.cuota_mantenimiento AS cuota,
    (p.fecha_ingreso IS NOT NULL AND p.fecha_ingreso > v_inicio AND p.fecha_ingreso <= v_fin) AS prorrateada,
    CASE
      WHEN p.fecha_ingreso IS NOT NULL AND p.fecha_ingreso > v_inicio AND p.fecha_ingreso <= v_fin THEN
        round(coalesce(u.cuota_mantenimiento, 0) * ((v_fin - p.fecha_ingreso)::numeric + 1) / v_dias_periodo, 2)
      WHEN p.fecha_ingreso IS NOT NULL AND p.fecha_ingreso > v_fin THEN
        0
      ELSE
        coalesce(u.cuota_mantenimiento, 0)
    END AS monto_calculado,
    EXISTS (
      SELECT 1 FROM public.facturas f2
       WHERE f2.unidad_id = u.id
         AND f2.periodo = p_periodo
         AND lower(f2.tipo_factura) IN ('mantenimiento','administracion','administración','mantenimiento mensual')
         AND lower(f2.estado) <> 'anulada'
    ) AS ya_facturada
  FROM public.unidades u
  LEFT JOIN public.propietarios p ON p.id = u.propietario_id
  WHERE u.condominio_id = p_condominio_id
    AND coalesce(u.cuota_mantenimiento, 0) > 0
  ORDER BY u.codigo;
END $function$
;

