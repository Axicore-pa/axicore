CREATE OR REPLACE FUNCTION private.axi_dump(p_tablas text[])
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE r text; out jsonb := '{}'::jsonb; j jsonb;
BEGIN
