CREATE OR REPLACE FUNCTION public.portal_morosidad_global(p_condominio_id bigint)
 RETURNS TABLE(unidades_total integer, unidades_en_mora integer, pct_unidades_en_mora numeric, monto_vencido numeric, monto_exigible numeric, pct_monto_en_mora numeric, fecha_corte date)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v_hoy date := (now() AT TIME ZONE 'America/Santo_Domingo')::date;
BEGIN
  IF NOT (private.es_ceo() OR p_condominio_id = ANY (private.condos_propietario())) THEN
    RAISE EXCEPTION 'Disponible solo para propietarios' USING ERRCODE = '42501'; END IF;
  RETURN QUERY
  WITH f AS (
    SELECT x.unidad_id, x.monto, x.balance_pendiente FROM public.facturas x
     WHERE x.condominio_id = p_condominio_id AND x.estado_aprobacion = 'Aprobado'
       AND lower(x.estado) <> 'anulada' AND lower(coalesce(x.tipo_facturacion, '')) = 'propietario'
       AND coalesce(x.tipo_factura, '') NOT ILIKE '%GLP%'
       AND x.fecha_vencimiento IS NOT NULL AND x.fecha_vencimiento < v_hoy),
  u AS (SELECT count(*)::int AS n FROM public.unidades y WHERE y.condominio_id = p_condominio_id),
  m AS (SELECT count(DISTINCT f.unidad_id) FILTER (WHERE f.balance_pendiente > 0)::int AS n,
               coalesce(sum(f.balance_pendiente), 0) AS venc, coalesce(sum(f.monto), 0) AS exig FROM f)
  SELECT u.n, m.n, CASE WHEN u.n > 0 THEN round(100.0 * m.n / u.n, 1) ELSE 0 END,
         m.venc, m.exig, CASE WHEN m.exig > 0 THEN round(100.0 * m.venc / m.exig, 1) ELSE 0 END, v_hoy
    FROM u, m;
END $function$
;

CREATE OR REPLACE FUNCTION public.portal_registrar_comprobante(p_factura_id bigint, p_fecha_pago date, p_monto numeric, p_archivo_ruta text, p_metodo text DEFAULT 'Transferencia'::text, p_banco text DEFAULT NULL::text, p_referencia text DEFAULT NULL::text, p_nota text DEFAULT NULL::text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE f record; es_dueno boolean; cid bigint; inq bigint;
BEGIN
  IF NOT private.es_residente() THEN RAISE EXCEPTION 'Solo propietarios e inquilinos' USING ERRCODE = '42501'; END IF;
  SELECT x.id, x.condominio_id, x.unidad_id, x.propietario_id, x.inquilino_id, x.no_factura INTO f FROM public.facturas x WHERE x.id = p_factura_id;
  IF f.id IS NULL THEN RAISE EXCEPTION 'Factura no encontrada' USING ERRCODE = '22023'; END IF;
  es_dueno := coalesce(f.unidad_id = ANY (private.unidades_propias()), false);
  IF NOT coalesce(es_dueno OR f.inquilino_id = ANY (private.mis_inquilinos()), false) THEN RAISE EXCEPTION 'Esa factura no le pertenece' USING ERRCODE = '42501'; END IF;
  IF p_monto IS NULL OR p_monto <= 0 OR p_monto > 10000000 THEN RAISE EXCEPTION 'Monto no valido' USING ERRCODE = '22023'; END IF;
  IF p_fecha_pago IS NULL OR p_fecha_pago > (now() AT TIME ZONE 'America/Santo_Domingo')::date OR p_fecha_pago < date '2020-01-01' THEN
    RAISE EXCEPTION 'Fecha de pago no valida' USING ERRCODE = '22023'; END IF;
  IF p_archivo_ruta IS NULL OR (storage.foldername(p_archivo_ruta))[1] IS DISTINCT FROM (SELECT auth.uid())::text
     OR NOT EXISTS (SELECT 1 FROM storage.objects o WHERE o.bucket_id = 'comprobantes' AND o.name = p_archivo_ruta) THEN
    RAISE EXCEPTION 'Suba primero el archivo del comprobante' USING ERRCODE = '22023'; END IF;
  IF EXISTS (SELECT 1 FROM public.comprobantes_pago c WHERE c.archivo_ruta = p_archivo_ruta) THEN
    RAISE EXCEPTION 'Este comprobante ya fue enviado' USING ERRCODE = '23505'; END IF;
  IF NOT es_dueno THEN inq := f.inquilino_id; END IF;
  INSERT INTO public.comprobantes_pago (condominio_id, factura_id, unidad_id, propietario_id, inquilino_id, subido_por, fecha_pago, monto,
         metodo, banco, referencia, archivo_ruta, nota)
  VALUES (f.condominio_id, f.id, f.unidad_id, CASE WHEN es_dueno THEN f.propietario_id END, inq, (SELECT auth.uid()), p_fecha_pago, round(p_monto, 2),
         left(nullif(btrim(p_metodo), ''), 50), left(nullif(btrim(p_banco), ''), 120), left(nullif(btrim(p_referencia), ''), 120),
         p_archivo_ruta, left(nullif(btrim(p_nota), ''), 1000))
  RETURNING id INTO cid;
  PERFORM private.log_portal('Pagos', 'comprobantes_pago', cid, 'factura', NULL, f.no_factura, 'Creación', 'Comprobante de pago enviado desde el portal');
  RETURN cid;
END $function$
;

CREATE OR REPLACE FUNCTION public.portal_reportar_averia(p_descripcion text, p_tipo text DEFAULT 'Otro'::text, p_area_aplicacion text DEFAULT NULL::text, p_prioridad text DEFAULT 'Media'::text, p_unidad_id bigint DEFAULT NULL::bigint)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE mias bigint[] := private.unidades_propias() || private.unidades_inquilino();
        u bigint := p_unidad_id; un record; quien record; anio text := to_char(now() AT TIME ZONE 'America/Santo_Domingo', 'YYYY');
        n int; cod text; mid bigint; pri text := coalesce(nullif(btrim(p_prioridad), ''), 'Media'); des text := btrim(p_descripcion);
BEGIN
  IF NOT private.es_residente() THEN RAISE EXCEPTION 'Solo propietarios e inquilinos' USING ERRCODE = '42501'; END IF;
  IF u IS NULL THEN
    IF cardinality(mias) = 1 THEN u := mias[1]; ELSE RAISE EXCEPTION 'Indique la unidad del reporte' USING ERRCODE = '22023'; END IF;
  END IF;
  IF NOT coalesce(u = ANY (mias), false) THEN RAISE EXCEPTION 'Esa unidad no le pertenece' USING ERRCODE = '42501'; END IF;
  IF des IS NULL OR length(des) < 5 OR length(des) > 2000 THEN RAISE EXCEPTION 'Describa la averia (5 a 2000 caracteres)' USING ERRCODE = '22023'; END IF;
  IF pri NOT IN ('Alta','Media','Baja') THEN RAISE EXCEPTION 'Prioridad no valida (Alta, Media o Baja)' USING ERRCODE = '22023'; END IF;
  IF length(coalesce(p_tipo, '')) > 60 OR length(coalesce(p_area_aplicacion, '')) > 100 THEN RAISE EXCEPTION 'Texto demasiado largo' USING ERRCODE = '22023'; END IF;
  SELECT x.id, x.codigo, x.condominio_id INTO un FROM public.unidades x WHERE x.id = u;
  SELECT q.nombre, q.telefono, q.email INTO quien FROM (
    SELECT p.nombre, p.telefono, p.email, 1 AS orden FROM public.propietarios p WHERE p.id = ANY (private.mis_propietarios()) AND u = ANY (private.unidades_propias())
    UNION ALL
    SELECT i.nombre, i.telefono, i.email, 2 FROM public.inquilinos i WHERE i.id = ANY (private.mis_inquilinos()) AND i.unidad_id = u) q
  ORDER BY q.orden LIMIT 1;
  PERFORM pg_advisory_xact_lock(hashtext('axicore_codigo_reporte'));
  SELECT coalesce(max(substring(m.codigo FROM '^AXI-RPT-' || anio || '-([0-9]+)$')::int), 0) + 1 INTO n FROM public.mantenimientos m;
  cod := 'AXI-RPT-' || anio || '-' || lpad(n::text, 5, '0');
  INSERT INTO public.mantenimientos (condominio_id, unidad_id, codigo, tipo, prioridad, fecha_solicitud, estatus, descripcion, area_aplicacion,
         afecta_fondo_comun, reportante_nombre, reportante_telefono, reportante_email, estado_registro, created_at, reportado_por)
  VALUES (un.condominio_id, u, cod, coalesce(nullif(btrim(p_tipo), ''), 'Otro'), pri, now(), 'Abierto', des, nullif(btrim(p_area_aplicacion), ''),
         false, quien.nombre, quien.telefono, quien.email, 'Completado', now(), (SELECT auth.uid()))
  RETURNING id INTO mid;
  INSERT INTO public.mantenimiento_historial (mantenimiento_id, codigo_formulario, unidad_codigo, nombre_reportante, categoria, prioridad, estatus, fecha_cambio, accion, created_at)
  VALUES (mid, cod, un.codigo, quien.nombre, coalesce(nullif(btrim(p_tipo), ''), 'Otro'), pri, 'Abierto', now(), 'Creado desde el portal', now());
  PERFORM private.log_portal('Mantenimientos', 'mantenimientos', mid, NULL, NULL, cod, 'Creación', 'Averia reportada desde el portal');
  RETURN cod;
END $function$
;

CREATE OR REPLACE FUNCTION public.revisar_comprobante(p_comprobante_id bigint, p_estado text, p_comentario text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE c record;
BEGIN
  IF NOT private.es_ceo() THEN RAISE EXCEPTION 'Solo el CEO valida comprobantes de pago' USING ERRCODE = '42501'; END IF;
  SELECT x.id, x.condominio_id, x.estado INTO c FROM public.comprobantes_pago x WHERE x.id = p_comprobante_id;
  IF c.id IS NULL THEN RAISE EXCEPTION 'Comprobante no encontrado' USING ERRCODE = '22023'; END IF;
  IF p_estado NOT IN ('Validado','Rechazado') THEN RAISE EXCEPTION 'Estado no valido (Validado o Rechazado)' USING ERRCODE = '22023'; END IF;
  IF c.estado <> 'Pendiente' THEN RAISE EXCEPTION 'Este comprobante ya fue revisado' USING ERRCODE = '22023'; END IF;
  IF p_estado = 'Rechazado' AND nullif(btrim(p_comentario), '') IS NULL THEN RAISE EXCEPTION 'Indique el motivo del rechazo' USING ERRCODE = '22023'; END IF;
  UPDATE public.comprobantes_pago SET estado = p_estado, revisado_por = (SELECT auth.uid()), fecha_revision = now(),
         comentario_revision = nullif(btrim(p_comentario), ''), updated_at = now() WHERE id = c.id;
  PERFORM private.log_portal('Pagos', 'comprobantes_pago', c.id, 'estado', 'Pendiente', p_estado, 'Modificación', 'Comprobante revisado');
END $function$
;

