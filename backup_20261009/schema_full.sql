CREATE OR REPLACE FUNCTION public.fn_factura_anular(p_factura_id bigint, p_motivo text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE v_factura public.facturas; v_condos bigint[];
BEGIN
  v_condos := private.staff_condos('Facturacion', 'eliminar');
  SELECT * INTO v_factura FROM public.facturas f WHERE f.id = p_factura_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Factura % no existe', p_factura_id; END IF;
  IF NOT (v_factura.condominio_id = ANY (v_condos)) THEN RAISE EXCEPTION 'No tiene permiso para anular facturas en este condominio'; END IF;
  IF lower(v_factura.estado) = 'anulada' THEN RAISE EXCEPTION 'La factura ya esta anulada'; END IF;
