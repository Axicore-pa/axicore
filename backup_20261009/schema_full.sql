CREATE OR REPLACE FUNCTION public.portal_fondo_comun(p_condominio_id bigint)
 RETURNS TABLE(periodo text, ingresos numeric, egresos numeric, balance_periodo numeric, balance_acumulado numeric)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
BEGIN
  IF NOT coalesce(p_condominio_id = ANY (private.condos_propietario()) OR private.es_ceo()
          OR p_condominio_id = ANY (private.staff_condos('EstadoCuenta','ver')), false) THEN
    RAISE EXCEPTION 'Sin acceso a este condominio' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT m.periodo, m.ingresos, m.egresos, m.ingresos - m.egresos,
         sum(m.ingresos - m.egresos) OVER (ORDER BY m.periodo)
  FROM (SELECT to_char(l.fecha, 'YYYY-MM') AS periodo, sum(l.entrada) AS ingresos, sum(l.salida) AS egresos
        FROM public.libro_financiero l
        WHERE l.condominio_id = p_condominio_id AND l.afecta_fondo_comun
        GROUP BY 1) m
  ORDER BY m.periodo;
END $function$
;

CREATE OR REPLACE FUNCTION public.portal_gastos_fondo_comun(p_condominio_id bigint, p_desde date DEFAULT NULL::date, p_hasta date DEFAULT NULL::date)
 RETURNS TABLE(gasto_id bigint, fecha date, codigo text, categoria text, tipo_servicio text, area_aplicacion text, descripcion text, proveedor text, monto numeric, factura_proveedor text, facturas_soporte jsonb, foto_factura_url text, estado text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
BEGIN
  IF NOT coalesce(p_condominio_id = ANY (private.condos_propietario()) OR private.es_ceo()
          OR p_condominio_id = ANY (private.staff_condos('Gastos','ver')), false) THEN
    RAISE EXCEPTION 'Sin acceso a este condominio' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT g.id, g.fecha, g.codigo, g.categoria, g.tipo_servicio, coalesce(g.area_aplicacion_otro, g.area_aplicacion), g.descripcion,
         coalesce(pr.nombre_comercial, pr.nombre), g.monto, g.factura_proveedor,
         (SELECT coalesce(jsonb_agg(jsonb_build_object('no_factura', fg.no_factura, 'fecha', fg.fecha, 'monto', fg.monto,
                  'concepto', fg.concepto) ORDER BY fg.fecha, fg.id), '[]'::jsonb)
            FROM public.facturas_gastos fg WHERE fg.gasto_id = g.id),
         g.foto_factura_url, g.estado
    FROM public.gastos g LEFT JOIN public.proveedores pr ON pr.id = g.proveedor_id
   WHERE g.condominio_id = p_condominio_id AND g.afecta_fondo_comun AND g.estado_aprobacion = 'Aprobado'
