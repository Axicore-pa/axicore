;

CREATE OR REPLACE FUNCTION private.axi_dump_logic()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE out text := ''; r record;
BEGIN
  out := out || E'-- ===== FUNCTIONS (public + private) =====\n';
  FOR r IN SELECT pg_get_functiondef(p.oid) def
           FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
           WHERE n.nspname IN ('public','private') ORDER BY n.nspname,p.proname LOOP
    out := out || r.def||E';\n\n';
  END LOOP;
  out := out || E'-- ===== TRIGGERS =====\n';
  FOR r IN SELECT pg_get_triggerdef(t.oid) def FROM pg_trigger t
           JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace
           WHERE n.nspname='public' AND NOT t.tgisinternal ORDER BY c.relname,t.tgname LOOP
    out := out || r.def||E';\n';
  END LOOP;
  out := out || E'\n-- ===== RLS + POLICIES =====\n';
  FOR r IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
           WHERE n.nspname='public' AND c.relkind='r' AND c.relrowsecurity ORDER BY c.relname LOOP
    out := out || format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;',r.relname)||E'\n';
  END LOOP;
  FOR r IN SELECT tablename,policyname,permissive,roles,cmd,qual,with_check
           FROM pg_policies WHERE schemaname='public' ORDER BY tablename,policyname LOOP
    out := out || format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;',
             r.policyname,r.tablename,r.permissive,r.cmd,array_to_string(r.roles,','),
             CASE WHEN r.qual IS NOT NULL THEN ' USING ('||r.qual||')' ELSE '' END,
             CASE WHEN r.with_check IS NOT NULL THEN ' WITH CHECK ('||r.with_check||')' ELSE '' END)||E'\n';
  END LOOP;
  RETURN out;
END $function$
;

CREATE OR REPLACE FUNCTION private.axi_dump_schema()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE out text := ''; r record; cols text;
BEGIN
  out := out || '-- AXICORE schema dump '||now()::text||E'\nCREATE SCHEMA IF NOT EXISTS private;\n\n';
  out := out || E'-- ===== TABLES =====\n';
  FOR r IN SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
           WHERE n.nspname='public' AND c.relkind='r' AND c.relname<>'zz_axi_probe2' ORDER BY c.relname LOOP
    SELECT string_agg(format('  %I %s%s%s%s', a.attname,
             pg_catalog.format_type(a.atttypid,a.atttypmod),
             CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
             CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
             CASE WHEN a.attgenerated='s' THEN ' GENERATED ALWAYS AS ('||pg_get_expr(ad.adbin,ad.adrelid)||') STORED'
                  WHEN a.attidentity='' AND ad.adbin IS NOT NULL THEN ' DEFAULT '||pg_get_expr(ad.adbin,ad.adrelid)
                  ELSE '' END),
             E',\n' ORDER BY a.attnum)
      INTO cols FROM pg_attribute a LEFT JOIN pg_attrdef ad ON ad.adrelid=a.attrelid AND ad.adnum=a.attnum
      WHERE a.attrelid=r.oid AND a.attnum>0 AND NOT a.attisdropped;
    out := out || format('CREATE TABLE IF NOT EXISTS public.%I (',r.relname)||E'\n'||cols||E'\n);\n';
  END LOOP;
  out := out || E'\n-- ===== CONSTRAINTS =====\n';
  FOR r IN SELECT con.conname, rel.relname, pg_get_constraintdef(con.oid) def
           FROM pg_constraint con JOIN pg_class rel ON rel.oid=con.conrelid
           JOIN pg_namespace n ON n.oid=rel.relnamespace
           WHERE n.nspname='public' AND rel.relname<>'zz_axi_probe2'
           ORDER BY CASE con.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 ELSE 4 END, rel.relname LOOP
    out := out || format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;',r.relname,r.conname,r.def)||E'\n';
  END LOOP;
  out := out || E'\n-- ===== INDEXES =====\n';
  FOR r IN SELECT indexdef FROM pg_indexes WHERE schemaname='public'
           AND indexname NOT IN (SELECT conname FROM pg_constraint) ORDER BY tablename,indexname LOOP
    out := out || r.indexdef||E';\n';
  END LOOP;
  out := out || E'\n-- ===== POST-DATA: resincronizar secuencias IDENTITY (correr DESPUES de cargar los datos) =====\n';
  FOR r IN SELECT c.relname, a.attname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
           JOIN pg_attribute a ON a.attrelid=c.oid
           WHERE n.nspname='public' AND c.relkind='r' AND a.attidentity<>'' AND c.relname<>'zz_axi_probe2'
           ORDER BY c.relname LOOP
    out := out || format('-- SELECT setval(pg_get_serial_sequence(''public.%I'',''%I''), GREATEST((SELECT max(%I) FROM public.%I),1));',
                         r.relname,r.attname,r.attname,r.relname)||E'\n';
  END LOOP;
  RETURN out;
END $function$
;

