CREATE OR REPLACE FUNCTION public.axi_ecg_totales(p_condominio_id bigint DEFAULT NULL::bigint, p_desde date DEFAULT NULL::date, p_hasta date DEFAULT NULL::date)
 RETURNS TABLE(total_ingresos numeric, total_egresos numeric, balance numeric)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
BEGIN
  IF NOT (private.es_ceo() OR (p_condominio_id IS NOT NULL AND p_condominio_id = ANY (private.staff_condos('EstadoCuenta','ver')))) THEN
    RAISE EXCEPTION 'Sin acceso al estado de cuenta general' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  WITH base AS (
    SELECT lf.* FROM public.libro_financiero lf
     WHERE (p_condominio_id IS NULL OR lf.condominio_id = p_condominio_id)
       AND coalesce(lf.tipo_aplicacion, '') NOT ILIKE '%GLP%'
       AND coalesce(lf.tipo_movimiento, '') NOT ILIKE '%GLP%'
       AND (coalesce(lf.afecta_fondo_comun, false) OR coalesce(lf.afecta_estado_cuenta, false))
       AND (p_desde IS NULL OR lf.fecha >= p_desde) AND (p_hasta IS NULL OR lf.fecha <= p_hasta)),
  ing AS (SELECT coalesce(sum(b.entrada), 0) AS total FROM base b),
  egr AS (SELECT coalesce(sum(b.salida), 0) AS total FROM base b
           WHERE b.tipo_movimiento = 'Gasto operativo' AND coalesce(b.afecta_fondo_comun, false))
  SELECT ing.total, egr.total, ing.total - egr.total FROM ing, egr;
END $function$
;

